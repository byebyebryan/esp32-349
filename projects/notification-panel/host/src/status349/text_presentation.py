_SELECTORS = "\uFE0E\uFE0F"


def is_text_presentation_selector(text: str, index: int) -> bool:
    """Recognize a supported pair; leave malformed selector runs unchanged."""
    return (
        index > 0
        and text[index] in _SELECTORS
        and ord(text[index - 1]) in TEXT_PRESENTATION_BASES
        and (index + 1 == len(text) or text[index + 1] not in _SELECTORS)
    )


def strip_text_presentation(text: str) -> str:
    """Use supported text bases, preserving other selectors and all marks."""
    return "".join(
        char for index, char in enumerate(text)
        if not is_text_presentation_selector(text, index)
    )
